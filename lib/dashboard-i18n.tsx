type DashboardI18nContextValue = {
  language: DashboardLanguage;
  setLanguage: (language: DashboardLanguage) => void;
  t: (text: string) => string;
};

const DashboardI18nContext = createContext<DashboardI18nContextValue | null>(null);

const normalizeLanguage = (value?: string): DashboardLanguage => {
  const text = String(value || "").toLowerCase();
  if (text.includes("czech") || text.includes("cestina") || text.includes("cz")) return "Czech";
  if (text.includes("german") || text.includes("deutsch") || text.includes("de")) return "German";
  return "English";
};

const nodeSources = new WeakMap<Text, string>();
const elementAttrSources = new WeakMap<Element, Map<string, string>>();

const translatableAttributes = ["placeholder", "title", "aria-label"] as const;

function normalizeLookupKey(value: string) {
  return value.trim().replace(/…/g, "...").replace(/[’]/g, "'").replace(/\s+/g, " ");
}

function translateValue(value: string, language: DashboardLanguage) {
  const key = normalizeLookupKey(value);
  if (!key) return value;
  if (language === "English") return key;
  return translations[language][key] || key;
}

function getAttributeSource(element: Element, attribute: string, current: string) {
  let sources = elementAttrSources.get(element);
  if (!sources) {
    sources = new Map<string, string>();
    elementAttrSources.set(element, sources);
  }
  const source = sources.get(attribute) || current.trim();
  sources.set(attribute, source);
  return source;
}

function translateAttributes(language: DashboardLanguage) {
  if (typeof document === "undefined") return;

  translatableAttributes.forEach((attribute) => {
    document.querySelectorAll(`[${attribute}]`).forEach((element) => {
      const current = element.getAttribute(attribute) || "";
      const source = getAttributeSource(element, attribute, current);
      const translated = translateValue(source, language);
      if (translated !== current.trim()) {
        element.setAttribute(attribute, translated);
      }
    });
  });
}

function translateDom(language: DashboardLanguage) {
  if (typeof document === "undefined") return;
  const dictionary = language === "English" ? null : translations[language];
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const textNode = node as Text;
      const parent = textNode.parentElement;
      if (!parent) return NodeFilter.FILTER_REJECT;
      if (["SCRIPT", "STYLE", "TEXTAREA", "INPUT", "OPTION"].includes(parent.tagName)) {
        return NodeFilter.FILTER_REJECT;
      }
      const text = textNode.textContent?.trim();
      if (!text) return NodeFilter.FILTER_REJECT;
      const source = nodeSources.get(textNode) || normalizeLookupKey(text);
      return dictionary?.[source] || source !== normalizeLookupKey(text) ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
    },
  });

  const nodes: Text[] = [];
  while (walker.nextNode()) nodes.push(walker.currentNode as Text);

  nodes.forEach((node) => {
    const current = node.textContent || "";
    const leading = current.match(/^\s*/)?.[0] || "";
    const trailing = current.match(/\s*$/)?.[0] || "";
    const source = nodeSources.get(node) || normalizeLookupKey(current);
    const translated = translateValue(source, language);
    if (translated !== normalizeLookupKey(current)) {
      nodeSources.set(node, source);
      node.textContent = `${leading}${translated}${trailing}`;
    }
  });

  translateAttributes(language);
}

export function DashboardI18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<DashboardLanguage>("English");

  useEffect(() => {
    setLanguageState(normalizeLanguage(window.localStorage.getItem(STORAGE_KEY) || "English"));
  }, []);

  const setLanguage = useCallback((nextLanguage: DashboardLanguage) => {
    const normalized = normalizeLanguage(nextLanguage);
    window.localStorage.setItem(STORAGE_KEY, normalized);
    setLanguageState(normalized);
  }, []);

  const t = useCallback(
    (text: string) => (language === "English" ? text : translations[language][text] || text),
    [language],
  );

  useEffect(() => {
    translateDom(language);
    const observer = new MutationObserver(() => translateDom(language));
    observer.observe(document.body, { childList: true, subtree: true, characterData: true });
    return () => observer.disconnect();
  }, [language]);

  const value = useMemo(() => ({ language, setLanguage, t }), [language, setLanguage, t]);

  return <DashboardI18nContext.Provider value={value}>{children}</DashboardI18nContext.Provider>;
}

export function useDashboardI18n() {
  const context = useContext(DashboardI18nContext);
  if (!context) {
    return {
      language: "English" as DashboardLanguage,
      setLanguage: () => undefined,
      t: (text: string) => text,
    };
  }
  return context;
}

